"""
EAIMOS Workflow Policies
=========================
Authorization policies for Workflows, Agents, and Integrations.
"""

import uuid
from typing import Union
from api.services.base.authorization import AuthorizationService
from api.services.base.service_context import ServiceContext
from api.services.base.permissions import EnterprisePermission


class WorkflowPolicy:
    @staticmethod
    def can_create(authorizer: AuthorizationService, ctx: ServiceContext, org_id: Union[uuid.UUID, str]) -> None:
        authorizer.require_authenticated(ctx)
        authorizer.require_tenant_access(ctx, org_id)
        authorizer.require_permission(ctx, EnterprisePermission.WORKFLOW_WRITE.value)

    @staticmethod
    def can_read(authorizer: AuthorizationService, ctx: ServiceContext, org_id: Union[uuid.UUID, str]) -> None:
        authorizer.require_authenticated(ctx)
        authorizer.require_tenant_access(ctx, org_id)
        authorizer.require_permission(ctx, EnterprisePermission.WORKFLOW_READ.value)

    @staticmethod
    def can_execute(authorizer: AuthorizationService, ctx: ServiceContext, org_id: Union[uuid.UUID, str]) -> None:
        authorizer.require_authenticated(ctx)
        authorizer.require_tenant_access(ctx, org_id)
        authorizer.require_permission(ctx, EnterprisePermission.WORKFLOW_EXECUTE.value)


class AgentPolicy:
    @staticmethod
    def can_manage(authorizer: AuthorizationService, ctx: ServiceContext, org_id: Union[uuid.UUID, str]) -> None:
        authorizer.require_authenticated(ctx)
        authorizer.require_tenant_access(ctx, org_id)
        authorizer.require_permission(ctx, EnterprisePermission.AGENT_MANAGE.value)

    @staticmethod
    def can_execute(authorizer: AuthorizationService, ctx: ServiceContext) -> None:
        authorizer.require_authenticated(ctx)
